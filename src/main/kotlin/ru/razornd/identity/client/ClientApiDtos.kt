package ru.razornd.identity.client

import com.fasterxml.jackson.annotation.JsonInclude
import jakarta.validation.Valid
import jakarta.validation.constraints.NotBlank
import jakarta.validation.constraints.NotEmpty
import jakarta.validation.constraints.Size

/** Request to register an OAuth2 client. Client credentials are generated by the service. */
@ValidClientRegistration
data class CreateClientRequest(
    @field:NotBlank
    @field:Size(max = 200)
    val clientName: String,
    @field:NotEmpty
    val clientAuthenticationMethods: Set<ClientAuthenticationMethod> = emptySet(),
    @field:NotEmpty
    val authorizationGrantTypes: Set<ClientAuthorizationGrantType> = emptySet(),
    val redirectUris: Set<String> = emptySet(),
    val scopes: Set<String> = emptySet(),
    @field:Valid
    val tokenSettings: ClientTokenSettingsRequest? = null,
)

/** Partial update request for a registered OAuth2 client. */
@ValidClientUpdate
data class UpdateClientRequest(
    @field:NotBlankWhenPresent
    @field:Size(max = 200)
    val clientName: String? = null,
    @field:Valid
    val clientAuthenticationMethods: SetChanges<ClientAuthenticationMethod>? = null,
    @field:Valid
    val authorizationGrantTypes: SetChanges<ClientAuthorizationGrantType>? = null,
    @field:Valid
    val redirectUris: SetChanges<String>? = null,
    @field:Valid
    val scopes: SetChanges<String>? = null,
    @field:Valid
    val tokenSettings: ClientTokenSettingsRequest? = null,
)

/** Add/remove operations for one client metadata set. */
@DisjointSetChanges
data class SetChanges<T>(
    val add: Set<T> = emptySet(),
    val remove: Set<T> = emptySet(),
) {
    fun isEmpty() = add.isEmpty() && remove.isEmpty()

    fun <R> map(transform: (T) -> R) = SetChanges(
        add.mapTo(HashSet(), transform),
        remove.mapTo(HashSet(), transform)
    )
}

fun <T> SetChanges<T>?.orEmpty() = this ?: SetChanges()

fun <T> Set<T>.toAddChanges() = SetChanges(add = this)

operator fun <T> MutableSet<T>.plusAssign(changes: SetChanges<T>) {
    this += changes.add
    this -= changes.remove
}

/** Public client metadata. Client secrets are deliberately excluded. */
data class ClientResponse(
    val clientId: String,
    val clientName: String,
    val clientAuthenticationMethods: Set<ClientAuthenticationMethod>,
    val authorizationGrantTypes: Set<ClientAuthorizationGrantType>,
    val redirectUris: Set<String>,
    val scopes: Set<String>,
    val tokenSettings: ClientTokenSettings,
)

/** Creation response; the generated client secret is returned only once. */
data class CreatedClientResponse(
    val clientId: String,
    @field:JsonInclude(JsonInclude.Include.NON_NULL)
    val clientSecret: String?,
    val clientName: String,
    val clientAuthenticationMethods: Set<ClientAuthenticationMethod>,
    val authorizationGrantTypes: Set<ClientAuthorizationGrantType>,
    val redirectUris: Set<String>,
    val scopes: Set<String>,
    val tokenSettings: ClientTokenSettings,
)
